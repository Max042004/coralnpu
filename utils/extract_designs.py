#!/usr/bin/env python3
"""One-off migration helper: turn Bazel `chisel_cc_library` targets into mk/designs.mk.

Reads every BUILD file under hdl/chisel, evaluates `chisel_cc_library(...)` and
`template_rule(chisel_cc_library, {...})` calls (BUILD files are valid Python),
and emits one Make stanza per generated design:

    DESIGNS += CoreMiniAxi
    CoreMiniAxi_EMIT  := coralnpu.EmitCore
    CoreMiniAxi_FLAGS := --fetchDataBits=128 ...
    CoreMiniAxi_VOPTS := -DUSE_GENERIC ...

Kept in the tree so the table can be regenerated while Bazel BUILD files still
exist for comparison; delete once the migration is complete.
"""
import ast
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def load_constants():
    env = {}
    for p in ROOT.glob("hdl/chisel/src/**/*.bzl"):
        try:
            exec(compile(p.read_text(), str(p), "exec"), {"__builtins__": {}}, env)
        except Exception:
            # load()-ing .bzl files are not executable here; constants only.
            for node in ast.parse(p.read_text()).body:
                if isinstance(node, ast.Assign):
                    try:
                        env[node.targets[0].id] = eval(
                            compile(ast.Expression(node.value), str(p), "eval"), {}, env)
                    except Exception:
                        pass
    return env


def collect(build_path, env):
    tree = ast.parse(build_path.read_text())
    # BUILD-local constants (e.g. flag lists).
    local = dict(env)
    for node in tree.body:
        if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
            try:
                local[node.targets[0].id] = eval(
                    compile(ast.Expression(node.value), "BUILD", "eval"), {}, local)
            except Exception:
                pass
    out = []

    def ev(n):
        return eval(compile(ast.Expression(n), "BUILD", "eval"), {}, local)

    for node in tree.body:
        if not (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)):
            continue
        c = node.value
        fn = getattr(c.func, "id", None)
        if fn == "chisel_cc_library":
            kw = {k.arg: ev(k.value) for k in c.keywords}
            out.append(kw)
        elif fn == "template_rule" and c.args and getattr(c.args[0], "id", "") == "chisel_cc_library":
            variants = ev(c.args[1])
            common = {k.arg: ev(k.value) for k in c.keywords}
            for name, over in variants.items():
                kw = dict(common)
                kw.update(over)
                kw["name"] = name
                out.append(kw)
    return out


def main():
    env = load_constants()
    stanzas = []
    for b in sorted(ROOT.glob("hdl/chisel/src/**/BUILD")):
        pkg = str(b.parent.relative_to(ROOT))
        for kw in collect(b, env):
            mod = kw["module_name"]
            stanzas.append((pkg, mod, kw))
    print("# Generated by utils/extract_designs.py from the former Bazel targets.")
    print("# <design>_EMIT  : main class of the generator (sbt runMain)")
    print("# <design>_FLAGS : arguments passed to the generator")
    print("# <design>_VOPTS : extra Verilator options for simulation builds")
    print("# <design>_OUTS  : extra files the generator writes next to <design>.sv")
    print()
    seen = set()
    for pkg, mod, kw in stanzas:
        if mod in seen:
            continue
        seen.add(mod)
        print(f"# {pkg}")
        print(f"DESIGNS += {mod}")
        print(f"{mod}_EMIT  := {kw['emit_class']}")
        print(f"{mod}_SV    := {kw.get('verilog_file_path') or mod + '.sv'}")
        flags = " ".join(kw.get("gen_flags", []))
        print(f"{mod}_FLAGS := {flags}")
        vopts = " ".join(kw.get("vopts", []))
        if vopts:
            print(f"{mod}_VOPTS := {vopts}")
        outs = " ".join(kw.get("extra_outs", []))
        if outs:
            print(f"{mod}_OUTS  := {outs}")
        print()


if __name__ == "__main__":
    sys.exit(main())
