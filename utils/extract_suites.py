#!/usr/bin/env python3
"""One-off migration helper: turn Bazel `cocotb_test_suite` targets into mk/cocotb_suites.mk.

    <suite>_MODEL   Verilated model (mk/models.mk) to run against
    <suite>_MODULE  Python module with the cocotb tests
    <suite>_CASES   individual testcases (informational)
Suites that need other simulators only (no verilator_model) are skipped.
"""
import ast
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def ev(node, env):
    try:
        return eval(compile(ast.Expression(node), "BUILD", "eval"), {}, env)
    except Exception:
        return None


def evd(node, env):
    """Like ev(), but a dict literal keeps the entries that do evaluate."""
    if isinstance(node, ast.Dict):
        out = {}
        for k, v in zip(node.keys, node.values):
            key = ev(k, env) if k is not None else None
            if isinstance(key, str):
                val = ev(v, env)
                if val is not None:
                    out[key] = val
        return out
    if isinstance(node, ast.Call) and getattr(node.func, "id", "") == "dict":
        out = {}
        for a in node.args:
            out.update(evd(a, env) or {})
        for k in node.keywords:
            val = ev(k.value, env)
            if k.arg and val is not None:
                out[k.arg] = val
        return out
    return ev(node, env)


def module_of(pkg, test_module):
    if isinstance(test_module, (list, tuple)):
        test_module = test_module[0] if test_module else None
    if not isinstance(test_module, str):
        return None
    t = test_module.lstrip(":").lstrip("/")
    if ":" in t:  # //pkg:file.py
        p, f = t.split(":", 1)
        pkg = p
        t = f
    stem = t[:-3] if t.endswith(".py") else t
    return (pkg + "/" + stem).replace("/", ".")


def main():
    suites = []
    for b in sorted(ROOT.glob("**/BUILD")):
        if not b.is_file() or {"third_party", "rules", "build", "target"} & set(b.parts):
            continue
        pkg = str(b.parent.relative_to(ROOT))
        tree = ast.parse(b.read_text())
        env = {}
        for node in tree.body:
            if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
                v = ev(node.value, env)
                if v is not None:
                    env[node.targets[0].id] = v
        for node in tree.body:
            if not (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)):
                continue
            c = node.value
            fn = getattr(c.func, "id", "")
            entries = []
            if fn == "cocotb_test_suite":
                kw = {k.arg: evd(k.value, env) for k in c.keywords}
                entries.append(kw)
            elif fn == "template_rule" and c.args and getattr(c.args[0], "id", "") == "cocotb_test_suite":
                variants = {}
                if isinstance(c.args[1], ast.Dict):
                    for k, v in zip(c.args[1].keys, c.args[1].values):
                        variants[ev(k, env)] = evd(v, env) or {}
                common = {k.arg: evd(k.value, env) for k in c.keywords}
                for name, over in variants.items():
                    kw = dict(common)
                    kw.update(over)
                    kw["name"] = name
                    entries.append(kw)
            for kw in entries:
                name = kw.get("name")
                tk = kw.get("tests_kwargs") or {}
                model = kw.get("verilator_model") or kw.get("model")
                if not isinstance(model, str):
                    continue
                module = module_of(pkg, tk.get("test_module") or kw.get("test_module"))
                cases = kw.get("testcases") or []
                cases = [c[0] if isinstance(c, tuple) else c for c in cases]
                suites.append((pkg, name, model.split(":")[-1], module, cases, tk.get("hdl_toplevel")))
    print("# Generated by utils/extract_suites.py from the former Bazel targets.")
    print("# Run one with: make cocotb-suite SUITE=<name>\n")
    for pkg, name, model, module, cases, top in suites:
        sid = f"{pkg.replace('/', '_')}_{name}".replace("-", "_")
        print(f"# {pkg}")
        print(f"COCOTB_SUITES += {sid}")
        print(f"{sid}_MODEL  := {model}")
        if not module and "core_mini_axi_sim_cocotb" in name:
            # test_module comes from a shared kwargs constant in the BUILD file.
            module = "tests.cocotb.core_mini_axi_sim"
        print(f"{sid}_MODULE := {module or 'UNKNOWN'}")
        print(f"{sid}_CASES  := {' '.join(cases)}")
        print()


if __name__ == "__main__":
    sys.exit(main())
