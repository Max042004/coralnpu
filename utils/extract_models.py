#!/usr/bin/env python3
"""One-off migration helper: turn Bazel `verilator_cocotb_model` targets into mk/models.mk.

    <model>_TOP    HDL toplevel module of the Verilated model
    <model>_DESIGN design in mk/designs.mk whose .sv is verilated
    <model>_CFLAGS Verilator arguments
    <model>_TRACE  1 to build with --trace
    <model>_VLT    verilator_config template (defaults to rules/default.vlt.tpl)
"""
import ast
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def load_constants():
    env = {}
    for p in list(ROOT.glob("hdl/**/*.bzl")) + list(ROOT.glob("tests/**/*.bzl")):
        for node in ast.parse(p.read_text()).body:
            if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
                try:
                    env[node.targets[0].id] = eval(
                        compile(ast.Expression(node.value), str(p), "eval"), {}, env)
                except Exception:
                    pass
    return env


def main():
    env = load_constants()
    seen = {}
    print("# Generated by utils/extract_models.py from the former Bazel targets.")
    print("# Verilated cocotb models: see mk/model.mk.\n")
    for b in sorted(ROOT.glob("**/BUILD")):
        if not b.is_file() or "third_party" in b.parts or "rules" in b.parts or "build" in b.parts:
            continue
        tree = ast.parse(b.read_text())
        local = dict(env)
        for node in tree.body:
            if isinstance(node, ast.Assign) and isinstance(node.targets[0], ast.Name):
                try:
                    local[node.targets[0].id] = eval(
                        compile(ast.Expression(node.value), "BUILD", "eval"), {}, local)
                except Exception:
                    pass
        for node in tree.body:
            if not (isinstance(node, ast.Expr) and isinstance(node.value, ast.Call)
                    and getattr(node.value.func, "id", "") == "verilator_cocotb_model"):
                continue
            kw = {}
            for k in node.value.keywords:
                try:
                    kw[k.arg] = eval(compile(ast.Expression(k.value), "BUILD", "eval"), {}, local)
                except Exception as e:
                    kw[k.arg] = None
            name = kw["name"]
            if name in seen:
                sys.stderr.write(f"duplicate model name {name} in {b} and {seen[name]}\n")
                continue
            seen[name] = str(b)
            src = kw.get("verilog_source") or ""
            design = re.sub(r"\.sv$", "", src.split(":")[-1]) if src else ""
            if design.endswith("_emit_verilog"):
                design = kw["hdl_toplevel"]  # generated by the same-named design
            vlt = kw.get("vlt_tpl")
            vlt = vlt.replace("//", "").replace(":", "/") if vlt else ""
            print(f"# {b.parent.relative_to(ROOT)}")
            print(f"MODELS += {name}")
            print(f"{name}_TOP    := {kw['hdl_toplevel']}")
            print(f"{name}_DESIGN := {design}")
            print(f"{name}_CFLAGS := {' '.join(kw.get('cflags') or [])}")
            print(f"{name}_TRACE  := {1 if kw.get('trace') else 0}")
            if vlt:
                print(f"{name}_VLT    := {vlt}")
            if not design:
                print(f"# NOTE: verilog_source not a simple label: {src!r} / "
                      f"verilog_sources={kw.get('verilog_sources')!r}")
            print()


if __name__ == "__main__":
    main()
